"""Защита от prompt injection на уровне текста: чистка поддельных тегов у источников и промпта."""
import re

_PROMPT_TAG_RE = re.compile(r"</?\s*news\s*>", re.IGNORECASE)
# Пост не должен суметь подделать наши собственные маркеры разметки промпта и выдать себя за
# другой источник/фото или разорвать блок <news> раньше времени. ID вида Sxx/Pxx нашей
# внутренней нумерации у постов взяться неоткуда, кроме подделки, поэтому просто вырезаем
# любой похожий тег из СЫРОГО текста поста до того, как обернуть его настоящим тегом.
_FAKE_PROVENANCE_TAG_RE = re.compile(r"\[(?:Фото|Пост)\s*:?\s*[SP]\d+[^\]]*\]", re.IGNORECASE)


def _neutralize_prompt_delimiters(text: str) -> str:
    """Пост не должен суметь «закрыть» блок <news> и продолжить своим текстом как инструкцией."""
    return _PROMPT_TAG_RE.sub("", text)


def _strip_fake_provenance_tags(text: str) -> str:
    """Убирает из СЫРОГО текста поста подделки под наши теги «[Фото: Pxx]»/«[Пост Sxx ...]»."""
    return _FAKE_PROVENANCE_TAG_RE.sub("", text)
